final Map<String, AppIconOption> _byKey = {
  for (final group in iconCatalog)
    for (final option in group.icons) option.key: option,
};

/// The catalog entry for a stored key (or a category name), if any.
AppIconOption? catalogIconFor(String? key) {
  final normalized = key?.trim().toLowerCase();
  if (normalized == null || normalized.isEmpty) return null;
  return _byKey[normalized] ?? _byKey[_aliases[normalized]];
}

/// The key the picker should show as selected for a stored key.
String? canonicalIconKey(String? key) => catalogIconFor(key)?.key;
