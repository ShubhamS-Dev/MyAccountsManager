import 'package:flutter/material.dart';

/// One pickable icon. [key] is what gets stored in `icon_key`.
class AppIconOption {
  const AppIconOption(this.key, this.label, this.icon, [this.tags = '']);

  final String key;
  final String label;
  final IconData icon;

  /// Extra search words, space separated.
  final String tags;

  bool matches(String query) {
    final haystack = '$key $label $tags'.toLowerCase();
    return query
        .toLowerCase()
        .split(RegExp(r'\s+'))
        .where((word) => word.isNotEmpty)
        .every(haystack.contains);
  }
}

